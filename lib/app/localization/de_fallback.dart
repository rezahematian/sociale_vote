/// Transitional localization helper for legacy inline IT/EN/DE copy.
///
/// New UI should still prefer AppLocalizations/ARB. Existing call sites keep
/// their Italian branch and German argument unchanged. This central fallback
/// prevents Persian, Spanish, Portuguese, French, Arabic and Romanian from silently falling back to
/// English on legacy surfaces while those strings are migrated to ARB.
String deOrEnglish(
  BuildContext context, {
  required String english,
  required String german,
}) {
  final languageCode =
      Localizations.localeOf(context).languageCode.toLowerCase();

  if (languageCode == 'de') {
    return german;
  }

  if (languageCode == 'fa' ||
      languageCode == 'es' ||
      languageCode == 'pt' ||
      languageCode == 'fr' ||
      languageCode == 'ar' ||
      languageCode == 'ro') {
    final dynamicTranslation = _legacyDynamicTranslation(
      languageCode,
      english,
    );
    if (dynamicTranslation != null) {
      return dynamicTranslation;
    }

    final table = switch (languageCode) {
      'fa' => _legacyFa,
      'es' => _legacyEs,
      'pt' => _legacyPt,
      'fr' => _legacyFr,
      'ar' => _legacyAr,
      'ro' => _legacyRo,
      _ => const <String, String>{},
    };
    return table[english] ?? english;
  }

  return english;
}

