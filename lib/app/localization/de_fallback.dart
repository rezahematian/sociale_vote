      pt: 'Para $action, entre ou crie uma conta. Como convidado, você pode navegar pelo conteúdo público.',
      fr: 'Pour $action, connectez-vous ou créez un compte. En tant qu’invité, vous pouvez parcourir le contenu public.',
      ar: 'من أجل $action، سجّل الدخول أو أنشئ حسابًا. كضيف يمكنك تصفح المحتوى العام.',
      ro: 'Pentru $action, autentifică-te sau creează un cont. Ca invitat poți explora conținutul public.',
    );
  }

  if (english.startsWith('To ') &&
      english.endsWith(
        ', sign in or create an account. As a guest you can only view content.',
      )) {
    const suffix =
        ', sign in or create an account. As a guest you can only view content.';
    final action = english.substring(3, english.length - suffix.length);
    return localized(
      fa: 'برای $action، وارد شوید یا یک حساب ایجاد کنید. به‌عنوان مهمان فقط می‌توانید محتوا را مشاهده کنید.',
      es: 'Para $action, inicia sesión o crea una cuenta. Como invitado solo puedes ver contenido.',
      pt: 'Para $action, entre ou crie uma conta. Como convidado, você só pode visualizar conteúdo.',
      fr: 'Pour $action, connectez-vous ou créez un compte. En tant qu’invité, vous pouvez uniquement consulter le contenu.',
      ar: 'من أجل $action، سجّل الدخول أو أنشئ حسابًا. كضيف يمكنك عرض المحتوى فقط.',
      ro: 'Pentru $action, autentifică-te sau creează un cont. Ca invitat poți doar vizualiza conținutul.',
    );
  }

  return null;
}

