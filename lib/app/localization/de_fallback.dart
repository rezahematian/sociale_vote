    );
  }

  if (english.startsWith('To ') &&
      english.endsWith(
        ', sign in or create an account. As a guest you can browse public content.',
      )) {
    const suffix =
        ', sign in or create an account. As a guest you can browse public content.';
    final action = english.substring(3, english.length - suffix.length);
    return localized(
      fa: 'برای $action، وارد شوید یا یک حساب ایجاد کنید. به‌عنوان مهمان می‌توانید محتوای عمومی را مرور کنید.',
