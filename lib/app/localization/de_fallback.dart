    ('Verified title: ', 'عنوان تأییدشده: ', 'Título verificado: ', 'Título verificado: ', 'Titre vérifié : ', 'صفة موثقة: ', 'Titlu verificat: '),
    ('Institution level: ', 'سطح نهاد: ', 'Nivel de la institución: ', 'Nível da instituição: ', 'Niveau de l’institution : ', 'مستوى المؤسسة: ', 'Nivelul instituției: '),
