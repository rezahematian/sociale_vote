    ('Location access error: ', 'خطای دسترسی به موقعیت: ', 'Error de acceso a la ubicación: ', 'Erro de acesso à localização: ', 'Erreur d’accès à la localisation : ', 'خطأ في الوصول إلى الموقع: ', 'Eroare la accesarea locației: '),
    ('The map is still filtered to ', 'نقشه همچنان روی این محدوده فیلتر شده است: ', 'El mapa sigue filtrado por: ', 'O mapa continua filtrado por: ', 'La carte reste filtrée sur ', 'لا تزال الخريطة مفلترة حسب ', 'Harta este în continuare filtrată după '),
    ('Show ', 'نمایش ', 'Mostrar ', 'Mostrar ', 'Afficher ', 'عرض ', 'Afișează '),
  ]) {
    if (english.startsWith(entry.$1)) {
      final suffix = english.substring(entry.$1.length);
      return localized(
        fa: '${entry.$2}$suffix',
        es: '${entry.$3}$suffix',
        pt: '${entry.$4}$suffix',
        fr: '${entry.$5}$suffix',
        ar: '${entry.$6}$suffix',
        ro: '${entry.$7}$suffix',
      );
    }
  }

  if (english.endsWith(' d') && RegExp(r'^\d+ d$').hasMatch(english)) {
