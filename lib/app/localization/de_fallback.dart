      english.length - 1,
    );
    return localized(
      fa: 'این Vote به‌عنوان $value منتشر می‌شود.',
      es: 'Este Vote se publicará como $value.',
      pt: 'Este Vote será publicado como $value.',
      fr: 'Ce Vote sera publié en tant que $value.',
      ar: 'سيتم نشر هذه Vote باسم $value.',
      ro: 'Acest Vote va fi publicat drept $value.',
    );
  }

  for (final entry in <(String, String, String, String, String, String, String)>[
