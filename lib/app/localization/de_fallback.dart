      ro: '$participants participanți · $responses răspunsuri · Raport $report',
    );
  }

  if (english.startsWith('Shows the most active content in ') &&
      english.endsWith(
        '. Account follows do not change this ranking.',
      )) {
    const tail = '. Account follows do not change this ranking.';
    final scope = english.substring(
      'Shows the most active content in '.length,
      english.length - tail.length,
    );
    return localized(
      fa: 'فعال‌ترین محتوا را در $scope نشان می‌دهد. دنبال‌کردن حساب‌ها این رتبه‌بندی را تغییر نمی‌دهد.',
