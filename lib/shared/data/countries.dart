  final String code; // ISO 3166-1 alpha-2
  final String name;

  const Country({
    required this.code,
    required this.name,
  });

  String localizedName(String languageCode) {
    return Countries.nameForCode(
      code,
      languageCode: languageCode,
      fallback: name,
    );
  }
}

