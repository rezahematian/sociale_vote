  static String nameForCode(
    String code, {
    required String languageCode,
    String? fallback,
  }) {
    final normalizedCode = code.trim().toUpperCase();
    if (normalizedCode.isEmpty) {
      return fallback ?? '';
    }

    final normalizedLanguage =
        languageCode.trim().toLowerCase().split(RegExp(r'[-_]')).first;

    final englishName =
        findByCode(normalizedCode)?.name ?? fallback ?? normalizedCode;

    if (normalizedLanguage == 'it') {
      return _italianNames[normalizedCode] ?? englishName;
    }

    if (normalizedLanguage == 'de') {
      return _germanNames[normalizedCode] ?? englishName;
    }

    if (normalizedLanguage == 'fa') {
      return _persianNames[normalizedCode] ?? englishName;
    }

    if (normalizedLanguage == 'es') {
      return _spanishNames[normalizedCode] ?? englishName;
    }

    if (normalizedLanguage == 'pt') {
      return _portugueseNames[normalizedCode] ?? englishName;
    }

    if (normalizedLanguage == 'fr') {
      return _frenchNames[normalizedCode] ?? englishName;
    }

    if (normalizedLanguage == 'ar') {
      return _arabicNames[normalizedCode] ?? englishName;
    }

    if (normalizedLanguage == 'ro') {
      return _romanianNames[normalizedCode] ?? englishName;
    }

    return englishName;
  }

  static Country? findByCode(String code) {
    try {
      return all.firstWhere(
        (c) => c.code.toUpperCase() == code.toUpperCase(),
      );
    } catch (_) {
      return null;
    }
  }
